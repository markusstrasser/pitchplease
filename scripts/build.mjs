// Build the shipped artifacts that are generated from sources in this repo.
//
//   node scripts/build.mjs                         regenerate engine/worklet.js from engine/processor.js + imports
//   node scripts/build.mjs --check                 exit 1 if engine/worklet.js is stale (the tests run this check)
//   node scripts/build.mjs --models <pitchtest/web>  also repack models/*.bin from pitchtest's exported weights
//
// models/<id>.bin keeps only the tensors the kernel reads (traced, not listed by hand) and records its source:
// the head checkpoint name and the sha256 of the manifest.json and weights.bin it was packed from.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { isDeepStrictEqual } from 'node:util';
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundle, verifyExports } from './bundle.mjs';
import { MODELS, packModel, unpackModel } from '../engine/models.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const WORKLET = join(ROOT, 'engine/worklet.js');
const PITCHTEST = process.env.PITCHTEST ?? join(ROOT, '../pitchtest');
const VERSION = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version;
const BANNER = `// GENERATED by scripts/build.mjs from engine/processor.js and the engine modules it imports. Do not edit:
// change the sources, then run \`npm run build\`. One self-contained file, because bundlers copy a worklet as an asset
// without its imports.`;

// Source weight folders (pitchtest/web/<dir>, written by pitchtest's web/export.py) for each model id.
export const MODEL_SOURCES = { fast: 'weights', piano: 'weights-bp8LR1', voice: 'weights-vpc' };

export const bundleWorklet = () => {
  const bundled = bundle(join(ROOT, 'engine/processor.js'), BANNER);
  bundled.code = bundled.code.replaceAll("'__PITCHPLEASE_VERSION__'", JSON.stringify(VERSION));
  return bundled;
};
export const workletSource = () => bundleWorklet().code;

/** Whether this file is the script node was asked to run (argv[1] may be a symlinked path, e.g. under /tmp). */
export function isMainModule(url) {
  try { return !!process.argv[1] && realpathSync(fileURLToPath(url)) === realpathSync(process.argv[1]); } catch { return false; }
}

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

/** Release consistency, using only files shipped in this repository. */
export function checkModels({ root = ROOT, models = MODELS } = {}) {
  const vendor = JSON.parse(readFileSync(join(root, 'engine/vendor.json'), 'utf8'));
  const problems = [];
  for (const id of Object.keys(MODEL_SOURCES)) {
    const model = models.find(m => m.id === id);
    if (!model) { problems.push(`${id}: missing from MODELS`); continue; }
    try {
      const file = readFileSync(join(root, 'models', `${id}.bin`));
      const { header, weights } = unpackModel(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength), id);
      const revision = sha256(Buffer.from(weights)).slice(0, 12);
      if (header.revision !== revision || model.revision !== revision) problems.push(`${id}: payload, header and MODELS revision differ`);
      if (!isDeepStrictEqual(header.threshold, model.threshold)) problems.push(`${id}: header threshold differs from MODELS threshold`);
      const entry = vendor.models?.[id];
      if (!entry || entry.revision !== revision || !isDeepStrictEqual(entry.threshold, model.threshold)) problems.push(`${id}: vendor.json revision or threshold differs`);
      if (!entry || !/^[0-9a-f]{40}$/.test(entry.commit) ||
          entry.dir !== `pitchtest/web/${MODEL_SOURCES[id]}` ||
          !['manifestSha256', 'weightsSha256'].every(k => /^[0-9a-f]{64}$/.test(entry[k])) ||
          ['dir', 'head', 'commit', 'manifestSha256', 'weightsSha256'].some(k => entry[k] !== header.source?.[k])) {
        problems.push(`${id}: vendor.json provenance differs from the header or lacks a full pitchtest commit`);
      }
    } catch (e) { problems.push(`${id}: ${e.message}`); }
  }
  return problems;
}

function kernelSource() {
  const vendor = JSON.parse(readFileSync(join(ROOT, 'engine/vendor.json'), 'utf8'));
  const hashes = { 'wasm-relaxed': vendor['incport-relaxed.wasm'].sha256, 'wasm-simd': vendor['incport.wasm'].sha256 };
  for (const [id, file] of [['wasm-relaxed', 'incport-relaxed.wasm'], ['wasm-simd', 'incport.wasm']]) {
    if (sha256(readFileSync(join(ROOT, 'engine', file))) !== hashes[id]) throw new Error(`engine/${file}: SHA-256 differs from vendor.json`);
  }
  const source = readFileSync(join(ROOT, 'engine/kernels.js'), 'utf8');
  const block = /^export const WASM_SHA256 = \{[^}]*\};/m;
  if (!block.test(source)) throw new Error('engine/kernels.js: missing generated WASM_SHA256 declaration');
  return source.replace(block, `export const WASM_SHA256 = {\n${Object.entries(hashes).map(([id, hash]) => `  '${id}': '${hash}',`).join('\n')}\n};`);
}

// Recorded operating points for these exact exported heads, rather than a neighbouring voice experiment.
const THRESHOLD_SOURCES = {
  fast: 'pitchtest/research/doe-train-vs-port.md:2305 (W10-L, latency rule: 0.7/0.42)',
  piano: 'pitchtest/research/doe-train-vs-port.md:2305 (BP8-LR1, latency rule: 0.6/0.36)',
  voice: 'pitchtest/logs/lv19-vpc-maestro_test.log:5 (VPC point: 0.65/0.39)',
};

async function packModels(webDir) {
  const pitchtest = join(webDir, '..');
  const git = (...args) => execFileSync('git', ['-C', pitchtest, ...args], { encoding: 'utf8' }).trim();
  const dirty = git('status', '--porcelain', '--', 'web/export.py', 'web/incport.js');
  if (dirty) throw new Error(`Refusing to build models: pitchtest web/export.py or web/incport.js has uncommitted changes:\n${dirty}`);
  const commit = git('rev-parse', 'HEAD');
  const vendorPath = join(ROOT, 'engine/vendor.json');
  const vendor = JSON.parse(readFileSync(vendorPath, 'utf8'));
  vendor.models ??= {};
  const { IMPLS } = await import('../engine/kernels.js');
  const kernel = IMPLS.js;
  for (const [id, dir] of Object.entries(MODEL_SOURCES)) {
    const manifestBytes = readFileSync(join(webDir, dir, 'manifest.json'));
    const weightsBytes = readFileSync(join(webDir, dir, 'weights.bin'));
    const manifest = JSON.parse(manifestBytes);
    const weights = kernel.parseWeights(manifest, weightsBytes.buffer.slice(weightsBytes.byteOffset, weightsBytes.byteOffset + weightsBytes.byteLength));
    // Trace which tensors the kernel reads while it builds a detector and runs a second of noise.
    const used = new Set();
    const traced = { ...weights, tensors: new Proxy(weights.tensors, { get(t, k) { if (typeof k === 'string' && k in t) used.add(k); return t[k]; } }) };
    const det = kernel.createDetector(traced, { inputRate: 48000 });
    const noise = new Float32Array(128);
    for (let i = 0; i < 48000; i += 128) { for (let j = 0; j < 128; j++) noise[j] = Math.sin(i + j) * 0.1; det.push(noise); }
    const names = Object.keys(manifest.tensors).filter((k) => used.has(k)).sort();
    const tensors = {};
    let size = 0;
    for (const k of names) { tensors[k] = { offset: size, shape: manifest.tensors[k].shape }; size += weights.tensors[k].length; }
    const data = new Float32Array(size);
    for (const k of names) data.set(weights.tensors[k], tensors[k].offset);
    const revision = sha256(Buffer.from(data.buffer)).slice(0, 12);
    const model = MODELS.find(m => m.id === id);
    if (revision !== model.revision) throw new Error(`${id}: weights revision ${revision} differs from MODELS ${model.revision}; update the registry before rebuilding`);
    const header = {
      model: id, tensors, const: manifest.const, revision, threshold: model.threshold,
      source: { dir: `pitchtest/web/${dir}`, head: manifest.const?.head ?? null, commit, manifestSha256: sha256(manifestBytes), weightsSha256: sha256(weightsBytes),
        dropped: Object.keys(manifest.tensors).filter((k) => !used.has(k)).sort() },
    };
    const bytes = packModel(header, data);
    const { dropped, ...source } = header.source;
    vendor.models[id] = { ...source, revision, threshold: model.threshold, thresholdSource: THRESHOLD_SOURCES[id] ?? 'engine/models.js MODELS (no pitchtest operating point found)' };
    writeFileSync(join(ROOT, 'models', `${id}.bin`), bytes);
    console.log(`models/${id}.bin  ${bytes.length} bytes (${Math.round(bytes.length / 1024)} KB)  kept ${names.length} tensors, dropped ${header.source.dropped.join(' ') || 'none'}`);
  }
  writeFileSync(vendorPath, JSON.stringify(vendor, null, 2) + '\n');
}

if (isMainModule(import.meta.url)) {
  const args = process.argv.slice(2);
  const generatedKernel = kernelSource();
  if (!args.includes('--check')) writeFileSync(join(ROOT, 'engine/kernels.js'), generatedKernel);
  const bundled = bundleWorklet();
  const problems = await verifyExports(bundled);
  if (problems.length) { for (const p of problems) console.error(`✗ ${p}`); process.exit(1); }
  const src = bundled.code;
  if (args.includes('--check')) {
    if (readFileSync(join(ROOT, 'engine/kernels.js'), 'utf8') !== generatedKernel) problems.push('engine/kernels.js integrity hashes are stale: run npm run build');
    problems.push(...checkModels());
    if (problems.length) { for (const p of problems) console.error(`✗ ${p}`); process.exit(1); }
    const cur = readFileSync(WORKLET, 'utf8');
    if (cur !== src) { console.error('engine/worklet.js is stale: run `npm run build`'); process.exit(1); }
    console.log('engine/worklet.js is up to date');
    console.log('models: revisions, payload hashes, thresholds and provenance agree');
  } else {
    writeFileSync(WORKLET, src);
    console.log(`engine/worklet.js  ${src.length} bytes`);
    const i = args.indexOf('--models');
    if (i >= 0) await packModels(args[i + 1] ?? join(PITCHTEST, 'web'));
  }
}
